  try { saved = localStorage.getItem(STORAGE_KEY); } catch { /* Preferences are optional. */ }
  const preferences = [saved, ...(navigator.languages || []), navigator.language];
  let language = preferences.map(normalize).find(Boolean) || 'en';

  function t(key, params = {}) {
    const value = catalogs[language][key] ?? catalogs.en[key] ?? key;
    return value.replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(params, name) ? String(params[name]) : placeholder);
  }
