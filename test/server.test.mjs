import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

test('LAN transfer lifecycle', async (t) => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'mckl-transfer-'));
  const child = spawn(process.execPath, [path.resolve('server.mjs')], { cwd: path.resolve('.'), env: { ...process.env, PORT: '0', SHARE_CODE: '123456', SHARE_DIR: dir }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(async () => { child.kill(); await rm(dir, { recursive: true, force: true }); });
  let output = '';
  const base = await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error(`server start timeout: ${output}`)), 5000);
    child.stdout.on('data', (chunk) => { output += chunk; const match = output.match(/http:\/\/localhost:(\d+)/); if (match) { clearTimeout(timeout); resolve(`http://127.0.0.1:${match[1]}`); } });
    child.on('error', reject);
  });
  const config = await fetch(`${base}/api/config`).then((r) => r.json());
  assert.equal(config.code, undefined, 'the access code must never be exposed by HTTP, including loopback');
  assert.equal(config.deviceName, undefined);
  assert.equal(config.version, '0.2.0-alpha.1');
  const bad = await fetch(`${base}/api/auth`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ code: '000000' }) });
  assert.equal(bad.status, 401);
  const auth = await fetch(`${base}/api/auth`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ code: '123456' }) });
  assert.equal(auth.status, 200);
  const cookie = auth.headers.get('set-cookie').split(';')[0];
  const authPayload = await auth.clone().json();
  assert.match(authPayload.clientId, /^[a-f0-9]{16}$/);
  const sentMessage = await fetch(`${base}/api/messages`, { method: 'POST', headers: { cookie, 'content-type': 'application/json' }, body: JSON.stringify({ text: 'Xin chào từ Mac' }) });
  assert.equal(sentMessage.status, 201);
  const message = await sentMessage.json();
  assert.equal(message.text, 'Xin chào từ Mac'); assert.equal(message.senderId, authPayload.clientId);
  const messageList = await fetch(`${base}/api/messages`, { headers: { cookie } }).then((r) => r.json());
  assert.equal(messageList.messages.length, 1); assert.equal(messageList.messages[0].id, message.id);
  const authPeer = await fetch(`${base}/api/auth`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ code: '123456' }) });
  const peerCookie = authPeer.headers.get('set-cookie').split(';')[0];
  const eventsResponse = await fetch(`${base}/api/events`, { headers: { cookie: peerCookie } });
  assert.equal(eventsResponse.status, 200);
  const reader = eventsResponse.body.getReader();
  const decoder = new TextDecoder();
  const readyChunk = await reader.read();
  assert.match(decoder.decode(readyChunk.value), /event: ready/);
  const chatEvent = (async () => {
    let received = '';
    while (true) {
      const chunk = await reader.read();
      if (chunk.done) return received;
      received += decoder.decode(chunk.value, { stream: true });
      if (received.includes('event: chat')) return received;
    }
  })();
  const liveMessage = await fetch(`${base}/api/messages`, { method: 'POST', headers: { cookie, 'content-type': 'application/json' }, body: JSON.stringify({ text: 'Tin nhắn realtime' }) });
  assert.equal(liveMessage.status, 201);
  let timeoutId;
  const receivedChat = await Promise.race([chatEvent, new Promise((_, reject) => { timeoutId = setTimeout(() => reject(new Error('SSE chat event timeout')), 3000); })]);
  clearTimeout(timeoutId);
  assert.match(receivedChat, /event: chat/); assert.match(receivedChat, /Tin nhắn realtime/);
  await reader.cancel();
  const emptyMessage = await fetch(`${base}/api/messages`, { method: 'POST', headers: { cookie, 'content-type': 'application/json' }, body: JSON.stringify({ text: '   ' }) });
  assert.equal(emptyMessage.status, 400);
  const body = Buffer.from('hello from mckl');
  const upload = await fetch(`${base}/api/upload`, { method: 'POST', headers: { cookie, 'x-file-name': encodeURIComponent('hello.txt'), 'x-file-size': String(body.length), 'x-file-type': 'text/plain' }, body });
  assert.equal(upload.status, 201);
  const file = await upload.json(); assert.equal(file.size, body.length); assert.match(file.hash, /^[a-f0-9]{64}$/);
  const list = await fetch(`${base}/api/files`, { headers: { cookie } }).then((r) => r.json()); assert.equal(list.files.length, 1);
  const downloaded = await fetch(`${base}/api/files/${file.id}/download`, { headers: { cookie } }).then((r) => r.arrayBuffer()); assert.deepEqual(Buffer.from(downloaded), body);
  const rangeResponse = await fetch(`${base}/api/files/${file.id}/download`, { headers: { cookie, range: 'bytes=6-9' } });
  assert.equal(rangeResponse.status, 206); assert.equal(rangeResponse.headers.get('content-range'), `bytes 6-9/${body.length}`); assert.deepEqual(Buffer.from(await rangeResponse.arrayBuffer()), Buffer.from('from'));
  const head = await fetch(`${base}/api/files/${file.id}/download`, { method: 'HEAD', headers: { cookie } }); assert.equal(head.status, 200); assert.equal(Number(head.headers.get('content-length')), body.length);
  const emptyUpload = await fetch(`${base}/api/upload`, { method: 'POST', headers: { cookie, 'x-file-name': 'empty.bin', 'x-file-size': '0', 'x-file-type': 'application/octet-stream' }, body: Buffer.alloc(0) });
  assert.equal(emptyUpload.status, 201);
  const emptyFile = await emptyUpload.json();
  const emptyDownload = await fetch(`${base}/api/files/${emptyFile.id}/download`, { headers: { cookie } });
  assert.equal(emptyDownload.status, 200); assert.equal(Number(emptyDownload.headers.get('content-length')), 0); assert.equal((await emptyDownload.arrayBuffer()).byteLength, 0);
  const duplicateBodies = [Buffer.from('one'), Buffer.from('two')];
  const duplicateUploads = await Promise.all(duplicateBodies.map((duplicateBody) => fetch(`${base}/api/upload`, { method: 'POST', headers: { cookie, 'x-file-name': 'duplicate.txt', 'x-file-size': String(duplicateBody.length), 'x-file-type': 'text/plain' }, body: duplicateBody })));
  assert.deepEqual(duplicateUploads.map((response) => response.status), [201, 201]);
  const duplicateFiles = await Promise.all(duplicateUploads.map((response) => response.json()));
  assert.notEqual(duplicateFiles[0].name.toLowerCase(), duplicateFiles[1].name.toLowerCase());
  const removed = await fetch(`${base}/api/files/${file.id}`, { method: 'DELETE', headers: { cookie } }); assert.equal(removed.status, 200);
  const removedEmpty = await fetch(`${base}/api/files/${emptyFile.id}`, { method: 'DELETE', headers: { cookie } }); assert.equal(removedEmpty.status, 200);
  await Promise.all(duplicateFiles.map((duplicateFile) => fetch(`${base}/api/files/${duplicateFile.id}`, { method: 'DELETE', headers: { cookie } })));
  const empty = await fetch(`${base}/api/files`, { headers: { cookie } }).then((r) => r.json()); assert.equal(empty.files.length, 0);
});
